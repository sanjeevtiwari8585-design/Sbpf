create table if not exists public.member_login_attempts (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  identifier_hash text not null,
  attempted_at timestamptz not null default now()
);
create index if not exists member_login_attempts_recent_idx on public.member_login_attempts (ip_hash, attempted_at desc);
create index if not exists member_login_attempts_identifier_recent_idx on public.member_login_attempts (identifier_hash, attempted_at desc);
alter table public.member_login_attempts enable row level security;
revoke all on public.member_login_attempts from anon, authenticated;
grant all on public.member_login_attempts to service_role;
