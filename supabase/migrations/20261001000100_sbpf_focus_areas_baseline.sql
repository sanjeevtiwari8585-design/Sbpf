-- Reconstructed SBPF focus_areas baseline
-- Local Docker validation only. Do not apply to Production.

CREATE TABLE public.focus_areas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    slug text UNIQUE,
    description text,
    image_url text,
    is_active boolean DEFAULT true,
    created_at timestamptz DEFAULT now(),
    display_order integer
);

CREATE UNIQUE INDEX focus_areas_display_order_unique_idx
ON public.focus_areas (display_order)
WHERE display_order IS NOT NULL;

ALTER TABLE public.focus_areas ENABLE ROW LEVEL SECURITY;

CREATE POLICY admin_all_focus_areas
ON public.focus_areas
FOR ALL TO authenticated
USING ((SELECT public.is_admin()))
WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY focus_areas_public_read_active
ON public.focus_areas
FOR SELECT TO anon, authenticated
USING (is_active = true);
