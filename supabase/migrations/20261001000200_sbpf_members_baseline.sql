CREATE OR REPLACE FUNCTION public.generate_member_id()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
  IF NEW.member_id IS NULL OR btrim(NEW.member_id) = '' THEN
    NEW.member_id := 'SBPF-' || to_char(current_date, 'YYYY') || '-' ||
      lpad(NEW.id::text, 6, '0');
  END IF;
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.generate_referral_code()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $function$
BEGIN
  IF NEW.referral_code IS NULL OR NEW.referral_code = '' THEN
    NEW.referral_code := 'SBPF' || LPAD(NEW.id::text, 6, '0');
  END IF;
  RETURN NEW;
END;
$function$;

CREATE OR REPLACE FUNCTION public.validate_member_referral()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
BEGIN
  IF NEW.referred_by_code IS NOT NULL AND btrim(NEW.referred_by_code) <> '' THEN
    IF NOT EXISTS (
      SELECT 1
      FROM public.members m
      WHERE m.referral_code = btrim(NEW.referred_by_code)
        AND (TG_OP = 'INSERT' OR m.id <> NEW.id)
    ) THEN
      RAISE EXCEPTION 'Invalid referral code';
    END IF;
    NEW.referred_by_code := btrim(NEW.referred_by_code);
  ELSE
    NEW.referred_by_code := NULL;
  END IF;

  RETURN NEW;
END;
$function$;

