CREATE OR REPLACE FUNCTION public.generate_member_referral_code()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  code text;
BEGIN
  LOOP
    code := 'SBPF-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
    EXIT WHEN NOT EXISTS (
      SELECT 1 FROM public.members WHERE referral_code = code
    );
  END LOOP;
  RETURN code;
END;
$function$;

