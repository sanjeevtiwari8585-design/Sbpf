-- Reconstructed SBPF youth empowerment services baseline
-- Based on read-only Production schema inspection.
-- Local Docker validation only. Do not apply to Production.

CREATE TABLE public.youth_empowerment_services (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_code text NOT NULL UNIQUE,
    service_name text NOT NULL,
    service_name_hi text NOT NULL,
    category text NOT NULL,
    short_description text NOT NULL,
    full_description text,
    eligibility text,
    delivery_mode text NOT NULL DEFAULT 'guidance'
        CHECK (delivery_mode IN ('information', 'guidance', 'referral_only', 'application_support', 'community_program')),
    availability_status text NOT NULL DEFAULT 'active'
        CHECK (availability_status IN ('active', 'referral_only', 'coming_soon', 'paused')),
    availability_note text,
    official_source_url text,
    application_url text,
    display_order integer NOT NULL DEFAULT 100,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX youth_empowerment_services_active_idx
ON public.youth_empowerment_services (is_active, display_order);

CREATE INDEX youth_empowerment_services_category_idx
ON public.youth_empowerment_services (category);

ALTER TABLE public.youth_empowerment_services ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins manage youth services"
ON public.youth_empowerment_services
FOR ALL TO authenticated
USING (public.is_admin())
WITH CHECK (public.is_admin());

CREATE POLICY "Public read active youth services"
ON public.youth_empowerment_services
FOR SELECT TO anon, authenticated
USING (is_active = true);

GRANT SELECT ON public.youth_empowerment_services TO anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.youth_empowerment_services TO authenticated;
GRANT ALL ON public.youth_empowerment_services TO service_role;
