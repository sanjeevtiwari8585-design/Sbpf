create or replace function public.sbpf_sync_team_member_snapshot()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  m public.members;
begin
  if new.member_row_id is null then
    select * into m
    from public.members
    where user_id = new.member_profile_id
    limit 1;
    if found then new.member_row_id := m.id; end if;
  else
    select * into m
    from public.members
    where id = new.member_row_id;
  end if;

  if found then
    new.member_id_snapshot := coalesce(m.member_id,new.member_id_snapshot);
    new.member_name_snapshot := coalesce(m.full_name,new.member_name_snapshot);
    new.country_snapshot := coalesce(m.country,'India');
    new.state_snapshot := m.state;
    new.district_snapshot := m.district;
    new.pincode_snapshot := m.pincode;
  end if;
  return new;
end;
$function$;

