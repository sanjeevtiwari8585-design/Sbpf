-- 8. Credit task coins only after an approval transition
create or replace function public.sbpf_rewards_on_submission_approved()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if new.status = 'approved' and old.status is distinct from 'approved' then
    if new.points_awarded <= 0 then
      raise exception 'Approved reward task must award positive SBPF Coins';
    end if;

    insert into public.sbpf_reward_wallet_ledger
      (member_profile_id,entry_type,reference_id,points_delta,description,created_by)
    values
      (new.member_profile_id,'task_reward',new.id,new.points_awarded,
       'Approved SBPF Rewards Zone task',(select auth.uid()))
    on conflict (entry_type,reference_id) do nothing;
  end if;
  return new;
end;
$function$;

