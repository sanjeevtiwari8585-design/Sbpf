-- Reconstructed SBPF work area content baseline
-- Intended for local Docker validation only.

CREATE TABLE public.work_area_content (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_area text NOT NULL,
    title text NOT NULL,
    description text,
    image_url text,
    link_url text,
    link_label text,
    content jsonb NOT NULL DEFAULT '{}'::jsonb,
    sort_order integer NOT NULL DEFAULT 0,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_work_area_content_area_active
ON public.work_area_content (work_area, is_active, sort_order);

ALTER TABLE public.work_area_content ENABLE ROW LEVEL SECURITY;

CREATE POLICY work_area_content_admin
ON public.work_area_content
FOR ALL TO authenticated
USING ((SELECT public.is_admin()))
WITH CHECK ((SELECT public.is_admin()));

CREATE POLICY work_area_content_public_read
ON public.work_area_content
FOR SELECT TO anon, authenticated
USING (is_active = true);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $function$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_work_area_content_updated_at
BEFORE UPDATE ON public.work_area_content
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

GRANT SELECT ON public.work_area_content TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.work_area_content TO authenticated;
GRANT ALL ON public.work_area_content TO service_role;