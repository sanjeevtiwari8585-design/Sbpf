-- SBPF local Reward Zone wallet baseline
begin;

create table if not exists public.sbpf_audit_log (
  id bigint generated by default as identity primary key,
  action text not null,
  module_key text,
  actor_user_id uuid references auth.users(id) on delete set null,
  entity_type text,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists sbpf_audit_log_actor_user_id_idx
on public.sbpf_audit_log(actor_user_id);

create index if not exists sbpf_audit_module_created_idx
on public.sbpf_audit_log(module_key, created_at desc);

alter table public.sbpf_audit_log enable row level security;

create policy sbpf_audit_read
on public.sbpf_audit_log for select to authenticated
using (public.is_admin());

create table if not exists public.sbpf_reward_wallets (
  member_profile_id uuid primary key references auth.users(id) on delete restrict,
  wallet_status text not null default 'active'
    check (wallet_status in ('active','locked','closed')),
  pin_hash text,
  pin_set_at timestamptz,
  failed_pin_attempts integer not null default 0 check (failed_pin_attempts >= 0),
  pin_locked_until timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.sbpf_reward_wallets enable row level security;

create policy sbpf_wallet_read_own
on public.sbpf_reward_wallets for select to authenticated
using (member_profile_id = (select auth.uid()));

create policy sbpf_wallet_admin_read
on public.sbpf_reward_wallets for select to authenticated
using (public.is_admin());

create policy sbpf_wallet_admin_update
on public.sbpf_reward_wallets for update to authenticated
using (public.is_admin()) with check (public.is_admin());

create table if not exists public.sbpf_reward_wallet_ledger (
  id uuid primary key default gen_random_uuid(),
  member_profile_id uuid not null references auth.users(id) on delete restrict,
  entry_type text not null check (entry_type in (
    'task_reward','admin_adjustment','redemption','reversal',
    'spin_reward','transfer_debit','transfer_credit',
    'product_redemption','watch_video_reward'
  )),
  reference_id uuid,
  points_delta integer not null check (points_delta <> 0),
  description text not null,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique (entry_type, reference_id)
);

create index if not exists sbpf_reward_ledger_member_idx
on public.sbpf_reward_wallet_ledger(member_profile_id, created_at desc);

create index if not exists sbpf_reward_wallet_ledger_created_by_idx
on public.sbpf_reward_wallet_ledger(created_by);

alter table public.sbpf_reward_wallet_ledger enable row level security;

create policy sbpf_reward_ledger_read_own_admin
on public.sbpf_reward_wallet_ledger for select to authenticated
using (member_profile_id = (select auth.uid()) or public.is_admin());

create policy sbpf_reward_ledger_admin_insert
on public.sbpf_reward_wallet_ledger for insert to authenticated
with check (public.is_admin());

create or replace function public.sbpf_rewards_admin_audit_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_old jsonb;
  v_new jsonb;
  v_id text;
  v_action text;
begin
  if tg_op = 'INSERT' then
    v_new := to_jsonb(new);
    v_id := coalesce(v_new->>'id', v_new->>'member_profile_id');
    v_action := 'insert';
  elsif tg_op = 'UPDATE' then
    v_old := to_jsonb(old);
    v_new := to_jsonb(new);
    v_id := coalesce(v_new->>'id', v_new->>'member_profile_id');
    v_action := 'update';
  else
    v_old := to_jsonb(old);
    v_id := coalesce(v_old->>'id', v_old->>'member_profile_id');
    v_action := 'delete';
  end if;

  insert into public.sbpf_audit_log
    (action,module_key,actor_user_id,entity_type,entity_id,metadata)
  values
    ('rewards_' || v_action,'rewards_zone',auth.uid(),tg_table_name,v_id,
     jsonb_build_object('old',v_old,'new',v_new,'source','database_trigger'));

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$function$;

create trigger sbpf_rewards_wallet_admin_audit
after insert or update or delete on public.sbpf_reward_wallets
for each row execute function public.sbpf_rewards_admin_audit_trigger();

revoke all on public.sbpf_reward_wallets from anon, authenticated;
grant select (
  member_profile_id, wallet_status, pin_set_at,
  failed_pin_attempts, pin_locked_until, created_at, updated_at
) on public.sbpf_reward_wallets to authenticated;

grant all on public.sbpf_reward_wallets to service_role;
grant select on public.sbpf_reward_wallet_ledger to authenticated;
grant all on public.sbpf_reward_wallet_ledger to service_role;
grant all on public.sbpf_audit_log to service_role;

commit;
