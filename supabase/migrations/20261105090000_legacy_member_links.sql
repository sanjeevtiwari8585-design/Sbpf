create table if not exists public.legacy_member_links (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  member_row_id bigint not null unique references public.members(id) on delete cascade,
  legacy_member_id text not null unique,
  legacy_membership_status text not null check (legacy_membership_status in ('active','expired','suspended','pending')),
  legacy_kyc_status text not null default 'unknown',
  legacy_member_name text,
  legacy_mobile_masked text,
  otp_verified_at timestamptz not null,
  last_checked_at timestamptz not null default now(),
  link_status text not null default 'linked' check (link_status in ('linked','revoked','review')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.legacy_member_links is
'Minimal server-managed link between an authenticated current SBPF member and a legacy portal Member ID. No raw phone, OTP, Aadhaar, PAN, or documents are stored.';

alter table public.legacy_member_links enable row level security;
revoke all on public.legacy_member_links from anon, authenticated;
grant select, insert, update, delete on public.legacy_member_links to service_role;
grant usage, select on sequence public.legacy_member_links_id_seq to service_role;

create index if not exists legacy_member_links_status_idx
  on public.legacy_member_links (link_status, legacy_membership_status);

create or replace function public.get_my_legacy_member_link()
returns table (
  legacy_member_id text,
  legacy_membership_status text,
  legacy_kyc_status text,
  legacy_member_name text,
  legacy_mobile_masked text,
  otp_verified_at timestamptz,
  link_status text
)
language sql
stable
security definer
set search_path = ''
as $$
  select l.legacy_member_id, l.legacy_membership_status, l.legacy_kyc_status,
         l.legacy_member_name, l.legacy_mobile_masked, l.otp_verified_at, l.link_status
  from public.legacy_member_links l
  where l.user_id = (select auth.uid())
    and l.link_status = 'linked'
  limit 1;
$$;

revoke all on function public.get_my_legacy_member_link() from public, anon;
grant execute on function public.get_my_legacy_member_link() to authenticated;
