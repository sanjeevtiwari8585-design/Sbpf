-- Reconstructed SBPF member certificates baseline
-- Based on read-only Production schema inspection.
-- Local Docker validation only. Do not apply to Production.

CREATE TABLE public.member_certificates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    member_id text NOT NULL,
    certificate_number text NOT NULL UNIQUE,
    certificate_type text NOT NULL DEFAULT 'membership'
        CHECK (certificate_type = 'membership'),
    certificate_status text NOT NULL DEFAULT 'pending'
        CHECK (certificate_status IN ('pending', 'issued', 'revoked')),
    issued_at timestamptz,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    verification_token uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE
);

CREATE INDEX member_certificates_member_id_idx
ON public.member_certificates (member_id);

CREATE INDEX member_certificates_user_id_idx
ON public.member_certificates (user_id);

ALTER TABLE public.member_certificates ENABLE ROW LEVEL SECURITY;

CREATE POLICY member_certificates_select_own
ON public.member_certificates
FOR SELECT TO authenticated
USING ((SELECT auth.uid()) = user_id);

GRANT SELECT ON public.member_certificates TO authenticated;
GRANT ALL ON public.member_certificates TO service_role;
